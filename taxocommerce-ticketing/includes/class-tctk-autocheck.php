<?php
/**
 * Dedicated functionality checks. A successful report requires an actual
 * ticket, message and attachment insert/read/delete cycle. No customer data
 * or outbound mail is used by this diagnostic.
 *
 * @package TaxoCommerceTicketing
 */
defined( 'ABSPATH' ) || exit;

final class TCTK_Autocheck {
    const NONCE = 'tctk_autocheck_run';

    public static function boot() {
        add_action( 'admin_post_tctk_autocheck_run', array( __CLASS__, 'run' ) );
        add_action( 'admin_post_tctk_autocheck_export', array( __CLASS__, 'export' ) );
    }

    private static function row( $check, $status, $details ) {
        return array( 'check' => $check, 'status' => $status, 'details' => $details );
    }

    private static function key() {
        return '_tctk_last_functionality_check';
    }

    private static function probe() {
        global $wpdb;
        $tables = TCTK_Ticketing::tables();
        $ticket_id = 0;
        $message_id = 0;
        $file_id = 0;
        $result = array();
        $success = false;
        $cleanup_ok = true;
        $mark = substr( hash( 'sha256', wp_generate_uuid4() ), 0, 18 );
        $now = current_time( 'mysql' );

        // A synthetic internal ticket cannot be seen through a public link.
        // Cleanup is limited to the exact IDs generated by this invocation.
        try {
            do {
            // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching -- Explicitly requested diagnostic of plugin-owned table.
            $created = $wpdb->insert( $tables['tickets'], array(
                'secret_hash' => str_repeat( '0', 64 ),
                'customer_name' => 'TaxoCommerce diagnostic',
                'customer_email' => '',
                'subject' => 'TCTK_CHECK_' . $mark,
                'category' => '',
                'status' => 'open',
                'priority' => 'normal',
                'visibility' => 'internal',
                'created_at' => $now,
                'updated_at' => $now,
            ) );
            $ticket_id = $created ? (int) $wpdb->insert_id : 0;
            if ( $ticket_id <= 0 ) {
                $result[] = self::row( 'ticket_insert_read', 'error', 'Could not insert a synthetic ticket.' );
                break;
            }
            // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching -- Verify synthetic ticket in current database.
            $stored_subject = $wpdb->get_var( $wpdb->prepare( 'SELECT subject FROM %i WHERE id = %d', $tables['tickets'], $ticket_id ) );
            if ( $stored_subject !== 'TCTK_CHECK_' . $mark ) {
                $result[] = self::row( 'ticket_insert_read', 'error', 'Synthetic ticket not readable after insert.' );
                break;
            }
            $result[] = self::row( 'ticket_insert_read', 'ok', 'A new synthetic ticket can be inserted and read.' );

            // Exercise the same message persistence service that public tickets use.
            $message_id = TCTK_Ticketing::add_message( $ticket_id, 'TaxoCommerce diagnostic', 'TCTK_CHECK_' . $mark, true, true );
            if ( $message_id <= 0 ) {
                $result[] = self::row( 'message_insert_read', 'error', 'Could not insert a synthetic message.' );
                break;
            }
            // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching -- Read synthetic message.
            $stored_body = $wpdb->get_var( $wpdb->prepare( 'SELECT body FROM %i WHERE id = %d AND ticket_id = %d', $tables['messages'], $message_id, $ticket_id ) );
            if ( $stored_body !== 'TCTK_CHECK_' . $mark ) {
                $result[] = self::row( 'message_insert_read', 'error', 'Synthetic message not readable after insert.' );
                break;
            }
            $result[] = self::row( 'message_insert_read', 'ok', 'A message can be inserted and read.' );

            // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching -- Private synthetic attachment, no uploads or files written.
            $created = $wpdb->insert( $tables['files'], array(
                'ticket_id' => $ticket_id,
                'message_id' => $message_id,
                'filename' => 'ticket-check.txt',
                'mime' => 'text/plain',
                'byte_count' => strlen( $mark ),
                'data' => $mark,
            ) );
            $file_id = $created ? (int) $wpdb->insert_id : 0;
            if ( $file_id <= 0 ) {
                $result[] = self::row( 'attachment_insert_read', 'error', 'Could not insert a synthetic attachment.' );
                break;
            }
            // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching -- Verify synthetic attachment bytes.
            $stored_data = $wpdb->get_var( $wpdb->prepare( 'SELECT data FROM %i WHERE id = %d AND ticket_id = %d', $tables['files'], $file_id, $ticket_id ) );
            if ( $stored_data !== $mark ) {
                $result[] = self::row( 'attachment_insert_read', 'error', 'Synthetic attachment bytes not readable.' );
                break;
            }
            $result[] = self::row( 'attachment_insert_read', 'ok', 'A private attachment can be inserted and read.' );
            $success = true;
            } while ( false );
        } finally {
            // Test cleanup must be verified, even after a read or insert failure.
            if ( $file_id ) {
                // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching -- Cleanup only the generated attachment ID.
                $cleanup_ok = 1 === $wpdb->delete( $tables['files'], array( 'id' => $file_id, 'ticket_id' => $ticket_id ), array( '%d', '%d' ) ) && $cleanup_ok;
            }
            if ( $message_id ) {
                // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching -- Cleanup only generated message.
                $cleanup_ok = 1 === $wpdb->delete( $tables['messages'], array( 'id' => $message_id, 'ticket_id' => $ticket_id ), array( '%d', '%d' ) ) && $cleanup_ok;
            }
            if ( $ticket_id ) {
                // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching -- Cleanup only generated ticket.
                $cleanup_ok = 1 === $wpdb->delete( $tables['tickets'], array( 'id' => $ticket_id, 'subject' => 'TCTK_CHECK_' . $mark ), array( '%d', '%s' ) ) && $cleanup_ok;
            }
            if ( ! $success || ! $cleanup_ok ) {
                TCTK_Event_Log::record( 'functional_probe_failed' );
            }
        }
        $result[] = self::row( 'probe_cleanup', $cleanup_ok ? 'ok' : 'error', $cleanup_ok ? 'Temporary diagnostic data was deleted.' : 'Diagnostic cleanup failed; check plugin tables for a TCTK_CHECK_ record.' );
        return $result;
    }

    /**
     * Run the functional test only by explicit admin action; synthetic test
     * writes never affect real tickets and never send messages.
     *
     * @return array
     */
    public static function report() {
        global $wpdb;
        $tables = TCTK_Ticketing::tables();
        $settings = TCTK_Ticketing::settings();
        $checks = array();
        $available = true;
        foreach ( $tables as $purpose => $name ) {
            // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching -- Live schema availability for plugin-owned tables.
            $found = $wpdb->get_var( $wpdb->prepare( 'SHOW TABLES LIKE %s', $wpdb->esc_like( $name ) ) );
            $ok = $found === $name;
            $available = $available && $ok;
            $checks[] = self::row( 'table_' . $purpose, $ok ? 'ok' : 'error', $ok ? 'Table available' : 'Table missing' );
        }
        $checks[] = self::row( 'staff_email', is_email( $settings['notification_email'] ) ? 'ok' : 'error', 'Checks notification email syntax only; does not send mail.' );
        $checks[] = self::row( 'form_link', ! empty( $settings['form_page_url'] ) ? 'ok' : 'warning', ! empty( $settings['form_page_url'] ) ? 'Public form URL configured.' : 'Set a form page URL before staff creates an external ticket.' );
        $checks[] = self::row( 'public_form', shortcode_exists( 'taxocommerce_ticket_form' ) ? 'ok' : 'error', 'Verifies registration of the public shortcode, not a browser submission.' );
        $checks[] = self::row( 'public_submission_route', has_action( 'admin_post_nopriv_tctk_submit' ) ? 'ok' : 'error', 'Verifies WordPress guest submission handler registration.' );
        $checks[] = self::row( 'reply_route', has_action( 'admin_post_nopriv_tctk_customer_reply' ) ? 'ok' : 'error', 'Verifies WordPress guest reply handler registration.' );
        if ( $available ) {
            // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery,WordPress.DB.DirectDatabaseQuery.NoCaching -- Aggregate counts only; no customer records disclosed in report.
            $count = (int) $wpdb->get_var( $wpdb->prepare( 'SELECT COUNT(*) FROM %i', $tables['tickets'] ) );
            $checks[] = self::row( 'existing_ticket_count', 'ok', sprintf( /* translators: %d: number of existing customer or internal tickets. */ __( '%d existing tickets in this WordPress database.', 'taxocommerce-ticketing' ), $count ) );
            $checks = array_merge( $checks, self::probe() );
        } else {
            $checks[] = self::row( 'ticket_insert_read', 'error', 'Not executed because one or more tables are missing.' );
            $checks[] = self::row( 'message_insert_read', 'error', 'Not executed because one or more tables are missing.' );
            $checks[] = self::row( 'attachment_insert_read', 'error', 'Not executed because one or more tables are missing.' );
        }
        $totals = array( 'ok' => 0, 'warning' => 0, 'error' => 0 );
        foreach ( $checks as $row ) {
            $totals[$row['status']]++;
        }
        return array(
            'plugin' => 'taxocommerce-ticketing',
            'version' => TCTK_VERSION,
            'type' => 'functionality',
            'executed_at' => gmdate( 'c' ),
            'rows' => $checks,
            'totals' => $totals,
            'email_delivery_tested' => false,
            'public_browser_submission_tested' => false,
            'customer_records_modified' => false,
        );
    }

    public static function run() {
        if ( ! current_user_can( TCTK_Ticketing::CAP ) ) {
            wp_die( esc_html__( 'Access denied.', 'taxocommerce-ticketing' ), '', array( 'response' => 403 ) );
        }
        check_admin_referer( self::NONCE );
        update_user_meta( get_current_user_id(), self::key(), self::report() );
        wp_safe_redirect( admin_url( 'admin.php?page=taxocommerce-ticketing&tab=autocheck&tctk_check=functionality' ) );
        exit;
    }

    public static function export() {
        if ( ! current_user_can( TCTK_Ticketing::CAP ) ) {
            wp_die( esc_html__( 'Access denied.', 'taxocommerce-ticketing' ), '', array( 'response' => 403 ) );
        }
        check_admin_referer( 'tctk_autocheck_export' );
        $report = get_user_meta( get_current_user_id(), self::key(), true );
        if ( ! is_array( $report ) ) {
            wp_die( esc_html__( 'Run the functionality check before exporting.', 'taxocommerce-ticketing' ), '', array( 'response' => 400 ) );
        }
        $json = wp_json_encode( $report, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE );
        if ( ! is_string( $json ) ) {
            wp_die( esc_html__( 'Unable to create JSON.', 'taxocommerce-ticketing' ) );
        }
        nocache_headers();
        header( 'Content-Type: application/json; charset=utf-8' );
        header( 'Content-Disposition: attachment; filename="taxocommerce-ticketing-functionality-check.json"' );
        // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- JSON attachment.
        echo $json;
        exit;
    }

    public static function render() {
        if ( ! current_user_can( TCTK_Ticketing::CAP ) ) {
            return;
        }
        $report = get_user_meta( get_current_user_id(), self::key(), true );
        echo '<h2>' . esc_html__( 'Functionality Check', 'taxocommerce-ticketing' ) . '</h2>';
        echo '<p>' . esc_html__( 'Checks plugin tables, shortcode and public handlers, then inserts, reads and deletes a private synthetic ticket, message and attachment. No real tickets are modified and no emails are sent. A separate browser/email test is still required.', 'taxocommerce-ticketing' ) . '</p>';
        echo '<form method="post" action="' . esc_url( admin_url( 'admin-post.php' ) ) . '"><input type="hidden" name="action" value="tctk_autocheck_run"/>';
        wp_nonce_field( self::NONCE );
        submit_button( __( 'Run Functionality Check', 'taxocommerce-ticketing' ) );
        echo '</form>';
        if ( ! is_array( $report ) ) {
            return;
        }
        echo '<p><strong>' . esc_html__( 'Date executed (UTC)', 'taxocommerce-ticketing' ) . ':</strong> ' . esc_html( $report['executed_at'] ) . '</p>';
        echo '<p>' . esc_html__( 'Passed:', 'taxocommerce-ticketing' ) . ' ' . esc_html( (string) $report['totals']['ok'] ) . ' · ' . esc_html__( 'Warnings:', 'taxocommerce-ticketing' ) . ' ' . esc_html( (string) $report['totals']['warning'] ) . ' · ' . esc_html__( 'Errors:', 'taxocommerce-ticketing' ) . ' ' . esc_html( (string) $report['totals']['error'] ) . '</p>';
        echo '<table class="widefat striped"><thead><tr><th>' . esc_html__( 'Check', 'taxocommerce-ticketing' ) . '</th><th>' . esc_html__( 'Status', 'taxocommerce-ticketing' ) . '</th><th>' . esc_html__( 'Details', 'taxocommerce-ticketing' ) . '</th></tr></thead><tbody>';
        foreach ( $report['rows'] as $row ) {
            echo '<tr><td>' . esc_html( $row['check'] ) . '</td><td>' . esc_html( $row['status'] ) . '</td><td>' . esc_html( $row['details'] ) . '</td></tr>';
        }
        echo '</tbody></table>';
        echo '<form method="post" action="' . esc_url( admin_url( 'admin-post.php' ) ) . '"><input type="hidden" name="action" value="tctk_autocheck_export"/>';
        wp_nonce_field( 'tctk_autocheck_export' );
        submit_button( __( 'Download Functionality JSON', 'taxocommerce-ticketing' ), 'secondary' );
        echo '</form>';
    }
}
